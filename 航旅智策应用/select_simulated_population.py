"""Verify retained 30,000 people independently of cancelled SFT.

Selection helpers document seeded proportional selection. The deleted candidate
pool cannot be regenerated by this verifier.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np
import independent_cohort as cohort
import marketing_ml as ml
from data_layer import RUNTIME, SOURCE, SOURCE_HASHES

SEED = 20261017
TRAIN_USERS = 26000
VALIDATION_USERS = TEST_USERS = 2000


def fingerprint(value):
    return hashlib.sha256(json.dumps(value,ensure_ascii=False,sort_keys=True,default=str).encode()).hexdigest()


def allocation(sizes,count):
    total=sum(sizes.values())
    if not 0<=count<=total:raise ValueError('Requested selection exceeds available people')
    if not total:return {key:0 for key in sizes}
    quotas={key:count*size//total for key,size in sizes.items()}
    order=sorted(sizes,key=lambda key:(-(count*sizes[key]%total),fingerprint([SEED,key])))
    for key in order[:count-sum(quotas.values())]:quotas[key]+=1
    return quotas


def stratum(source,user,dwell):
    mean=float(np.mean(dwell[:30]));activity='short' if mean<60 else 'medium' if mean<180 else 'long'
    return (source,user['usual_departure_city'],user.get('age_band','unknown'),user.get('travel_party','unknown'),activity)


def population_path():
    active=json.loads((RUNTIME/'synthetic-users/active.json').read_text(encoding='utf-8'))
    root=Path(active['root']).resolve()
    if not root.is_relative_to((RUNTIME/'synthetic-users').resolve()):raise ValueError('Population outside project')
    if cohort.digest(root/'manifest.json')!=active['manifest_sha256']:raise ValueError('Active population fingerprint changed')
    return root


def verify(population=None):
    root=Path(population) if population else population_path()
    catalog=json.loads((root/'manifest.json').read_text(encoding='utf-8'))
    if tuple(catalog[k] for k in ('total_users','training_users','validation_users','test_users'))!=(30000,26000,2000,2000):
        raise ValueError('Population count contract changed')
    original=ml.load_data();owners={u['user_id'] for u in original[1]}
    if len(owners)!=10000:raise ValueError('Original population changed')
    split_sets=[owners,set(),set()]
    entries=[(root/row['path'],row['users'],row['manifest_sha256'],0) for row in catalog['sources']]
    entries.extend((root/split,2000,None,i) for i,split in enumerate(('validation','test'),1))
    for directory,expected,sha,index in entries:
        if sha and cohort.digest(directory/'manifest.json')!=sha:raise ValueError('Fragment manifest changed')
        manifest=json.loads((directory/'manifest.json').read_text(encoding='utf-8'))
        for name,spec in manifest['files'].items():
            file=directory/name
            if file.stat().st_size!=spec['bytes'] or cohort.digest(file)!=spec['sha256']:raise ValueError('Raw file changed')
        users=[json.loads(line) for line in (directory/'users.jsonl').read_text(encoding='utf-8').splitlines()]
        ids={u['user_id'] for u in users}
        if len(ids)!=expected or len(users)!=expected or any(ids & prev for prev in split_sets):raise ValueError('Duplicate identities')
        if any(u.get('is_synthetic') not in (True,1) for u in users):raise ValueError('Real person in simulated data')
        if manifest['candidate_destinations']!=original[3]:raise ValueError('Candidate order differs')
        with np.load(directory/'behavior_arrays.npz',allow_pickle=False) as arrays:
            if any(arrays[k].shape!=(manifest['behavior_days'],expected) for k in arrays.files):raise ValueError('Raw behavior axes changed')
        split_sets[index].update(ids)
    if tuple(map(len,split_sets))!=(26000,2000,2000):raise ValueError('Split counts changed')
    for name,sha in SOURCE_HASHES.items():
        if cohort.digest(SOURCE/name)!=sha:raise ValueError('Original workbook changed')
    return dict(status='population_verified',total_users=30000,training_users=26000,validation_users=2000,
        test_users=2000,source_batches=len(catalog['sources']),owner_overlap=0,
        manifest_sha256=cohort.digest(root/'manifest.json'),original_workbooks_unchanged=True)


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--population',type=Path);args=parser.parse_args()
    print(json.dumps(verify(args.population),ensure_ascii=False,indent=2))
